/**
 * Regenerates lib/media.ts from _tools/media-manifest.json.
 *
 * Keeping this generated means the width/height attributes baked into the
 * markup can never drift from the files that build-media.py actually wrote —
 * which is what keeps CLS at zero.
 */
import { readFileSync, writeFileSync } from "node:fs";

const manifest = JSON.parse(readFileSync("_tools/media-manifest.json", "utf8"));

const groups = [];
for (const [key, entry] of Object.entries(manifest)) {
  const parts = [`    color: ${JSON.stringify(entry.color)},`];
  for (const kind of ["wide", "tall"]) {
    const list = entry[kind];
    if (!list) continue;
    parts.push(`    ${kind}: [`);
    for (const item of list) {
      parts.push(`      v(\`\${base}/${item.file}\`, ${item.w}, ${item.h}),`);
    }
    parts.push("    ],");
  }
  groups.push(`  ${key}: {\n${parts.join("\n")}\n  },`);
}

const out = `/**
 * Responsive image manifest — GENERATED by _tools/gen-media-ts.mjs.
 * Do not edit by hand: run
 *   python _tools/build-media.py && node _tools/gen-media-ts.mjs
 * after changing the media pipeline.
 *
 * Every entry is a pre-rendered WebP variant produced from the venue's own
 * photographs published on the company's 2GIS card. \`color\` is the dominant
 * tone, used as the placeholder background so the layout never flashes white
 * and never shifts (CLS = 0).
 */

export type MediaVariant = { src: string; w: number; h: number };

export type MediaEntry = {
  color: string;
  wide?: MediaVariant[];
  tall?: MediaVariant[];
};

const v = (src: string, w: number, h: number): MediaVariant => ({ src, w, h });
const base = "/media/v2";

export const media = {
${groups.join("\n")}
} satisfies Record<string, MediaEntry>;

export type MediaKey = keyof typeof media;
export type MediaKind = "wide" | "tall";

export function srcSet(entry: MediaEntry, kind: MediaKind): string {
  const list = entry[kind] ?? entry.wide ?? entry.tall ?? [];
  return list.map((i) => \`\${i.src} \${i.w}w\`).join(", ");
}

export function fallback(entry: MediaEntry, kind: MediaKind): MediaVariant {
  const list = entry[kind] ?? entry.wide ?? entry.tall ?? [];
  return list[Math.min(1, list.length - 1)];
}
`;

writeFileSync("lib/media.ts", out, "utf8");
console.log("lib/media.ts written:", out.length, "bytes");
